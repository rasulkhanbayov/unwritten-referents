#!/usr/bin/env python3
r"""
Regenerate the paper's data-bearing figures from records, as TikZ the manuscript
can \input directly. Two outputs:

  fig_risk_coverage.tex   the risk-coverage curve the paper does not have. Its
                          central object is selective risk at a coverage and it
                          currently reports three points from that curve.
  fig_offsets.tex         the offset sweep now in Figure 3, regenerated so the
                          figure and the records cannot drift apart.

Usage: python scripts/figures.py --config configs/experiments.yaml
"""
import argparse, sys
from pathlib import Path
import numpy as np, yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from skc import io, metrics, selectors

WONG = ["0072B2", "D55E00", "009E73", "E69F00", "CC79A7"]


def risk_coverage(cfg, out):
    cov = np.array(cfg["analysis"]["coverages"])
    lines, colours = [], {}
    for i, m in enumerate(cfg["data"]["models"][:1]):   # headline model only
        mid = m["id"]
        recs = io.load(cfg["data"]["root"], mid, "f1_twohop")
        fit, ev = recs.where(split="fit"), recs.where(split="eval")
        std = selectors.Standardizer("fit").fit(g_S=fit.col("g_S"), g_B=fit.col("g_B"))
        z = std.transform(g_S=ev.col("g_S"), g_B=ev.col("g_B"))
        Y = ev.col("Y")
        for j, name in enumerate(("surface_gate", "bgr_min", "bridge_only")):
            s = selectors.SELECTORS[name](z["g_S"], z["g_B"])
            r = metrics.risk_coverage_curve(s, Y, cov)
            colours[name] = WONG[j]
            pts = " ".join(f"({c:.2f},{v:.4f})" for c, v in zip(cov, r))
            lines.append(f"\\addplot[wong{j}, line width=1.1pt, mark=*, mark size=1.2pt] "
                         f"coordinates {{{pts}}};  %% {mid} {name}")
    body = "\n".join(lines)
    defs = "\n".join(f"\\definecolor{{wong{i}}}{{HTML}}{{{c}}}" for i, c in enumerate(WONG))
    (Path(out) / "fig_risk_coverage.tex").write_text(f"""% GENERATED by scripts/figures.py -- do not edit by hand.
\\begin{{tikzpicture}}
{defs}
\\begin{{axis}}[width=9.4cm, height=5.4cm,
  xlabel={{coverage $c$}}, ylabel={{selective risk $R$}},
  axis x line*=bottom, axis y line*=left, clip=false,
  tick label style={{font=\\sffamily\\scriptsize}},
  label style={{font=\\sffamily\\scriptsize}}]
{body}
\\end{{axis}}
\\end{{tikzpicture}}
""")
    print(f"  wrote {out}/fig_risk_coverage.tex")


def offsets(cfg, out):
    rows = []
    for i, m in enumerate(cfg["data"]["models"]):
        mid = m["id"]
        recs = io.load(cfg["data"]["root"], mid, "f1_twohop")
        ev = recs.where(split="eval")
        pts = []
        for off in cfg["bgr"]["offsets"]:
            sub = ev.where(offset=off)
            if len(sub) == 0:
                raise io.MissingData(
                    f"{mid}: no records at offset {off}. The sweep must be "
                    f"exported for every offset in configs/experiments.yaml, "
                    f"and the peak must be SELECTED on the validation split.")
            pts.append((off, metrics.auroc(sub.col("g_B"), sub.M(2))))
        rows.append((mid, WONG[i % len(WONG)], pts))
    body = "\n".join(
        f"\\addplot[wong{i}, line width=1.1pt, mark=*] coordinates "
        f"{{{' '.join(f'({o},{v:.4f})' for o, v in pts)}}};  %% {mid}"
        for i, (mid, _, pts) in enumerate(rows))
    print(f"  wrote {out}/fig_offsets.tex")
    (Path(out) / "fig_offsets.tex").write_text(
        "% GENERATED by scripts/figures.py -- do not edit by hand.\n" + body + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="configs/experiments.yaml")
    ap.add_argument("--out", default="results/figures")
    a = ap.parse_args()
    cfg = yaml.safe_load(open(a.config)); Path(a.out).mkdir(parents=True, exist_ok=True)
    for fn in (risk_coverage, offsets):
        try:
            fn(cfg, a.out)
        except io.MissingData as e:
            print(f"  SKIPPED {fn.__name__} -- {e}")


if __name__ == "__main__":
    main()
